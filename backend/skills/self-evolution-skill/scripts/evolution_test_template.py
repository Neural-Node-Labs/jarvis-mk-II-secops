def generate_report(output_path: str = None):
    total = len(RESULTS)
    passed = sum(1 for r in RESULTS if r["status"] == "PASS")
    failed = total - passed
    verdict = "ALL_PASS" if failed == 0 else "FAILURES_PRESENT"

    report_lines = [
        "# Evolution Test Report",
        f"Run at   : {iso_now()}",
        f"Suite    : evolution_test_{WORKSPACE_ID}",
        f"Verdict  : {verdict}",
        "",
        "| Test | Component | Scenario | Status | Duration |",
        "|------|-----------|----------|--------|----------|",
    ]
    for r in RESULTS:
        status_icon = "✓ PASS" if r["status"] == "PASS" else "✗ FAIL"
        report_lines.append(
            f"| {r['test_id']} | {r['component']} | {r['scenario']} | {status_icon} | {r['duration_seconds']}s |"
        )

    report_lines += [
        "",
        f"## Summary",
        f"Total: {total} | PASS: {passed} | FAIL: {failed}",
    ]

    if failed > 0:
        report_lines.append("\n## Failed Tests")
        for r in RESULTS:
            if r["status"] == "FAIL":
                report_lines.append(f"\n### {r['test_id']} — {r['component']}.{r['scenario']}")
                report_lines.append(f"```\n{r['error']}\n```")

    report_md = "\n".join(report_lines)
    print("\n" + "─" * 60)
    print(report_md)

    if output_path:
        with open(output_path, "w") as f:
            f.write(report_md)
        print(f"\nReport written to: {output_path}")

    # Write JSON results
    json_path = output_path.replace(".md", ".json") if output_path else None
    if json_path:
        with open(json_path, "w") as f:
            json.dump({
                "workspace_id": WORKSPACE_ID,
                "verdict": verdict,
                "summary": {"total": total, "passed": passed, "failed": failed},
                "results": RESULTS
            }, f, indent=2)

    return verdict


