def iso_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def run_test(test_id: str, component: str, scenario: str, fn: Callable) -> bool:
    start = time.perf_counter()
    status = "PASS"
    error_detail = None
    try:
        fn()
    except AssertionError as e:
        status = "FAIL"
        error_detail = f"Assertion failed: {e}"
    except Exception as e:
        status = "FAIL"
        error_detail = f"Exception: {type(e).__name__}: {e}\n{traceback.format_exc()}"
    duration = round(time.perf_counter() - start, 4)

    RESULTS.append({
        "test_id": test_id,
        "component": component,
        "scenario": scenario,
        "status": status,
        "duration_seconds": duration,
        "error": error_detail,
        "timestamp": iso_now()
    })

    icon = "✓" if status == "PASS" else "✗"
    print(f"  [{icon}] {test_id} | {component}.{scenario} | {duration}s")
    if error_detail:
        print(f"       {error_detail}")
    return status == "PASS"


